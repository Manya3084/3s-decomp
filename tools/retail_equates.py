#!/usr/bin/env python3
"""Prepare retail assembly for a byte-matching link.

Symbols inside the code image become labels, so branches assemble.
Symbols in the payload, BSS, or elsewhere become absolute .equ values.
"""

from __future__ import annotations

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TEXT = ROOT / "asm/retail/split/text.s"
LABELED = ROOT / "asm/retail/split/text.labeled.s"
OUT = ROOT / "asm/retail/split/equates.s"
SOURCES = [
    (ROOT / "config/retail/undefined_syms_auto.txt", "dlabel"),
    (ROOT / "config/retail/undefined_funcs_auto.txt", "glabel"),
]
# Retail LOAD code. Branches to these addresses must be real labels.
TEXT_LO = 0x100000
TEXT_HI = 0x373780
LINE = re.compile(r"^([A-Za-z_.$][\w.$]*)\s*=\s*(0x[0-9A-Fa-f]+)\s*;")
GLABEL = re.compile(r"^glabel\s+(\S+)")
VRAM = re.compile(r"/\*\s*[0-9A-Fa-f]+\s+([0-9A-Fa-f]+)\b")


def main() -> None:
    defined = set()
    for line in TEXT.open():
        match = GLABEL.match(line)
        if match:
            defined.add(match.group(1))

    # vram -> [(macro, name)] for symbols that live in the code image.
    # Everything else is an absolute address (%hi/%lo, jal into the payload).
    at_vram: dict[int, list[tuple[str, str]]] = {}
    equates: dict[str, int] = {}
    for path, macro in SOURCES:
        for line in path.read_text().splitlines():
            match = LINE.match(line.strip())
            if not match:
                continue
            name, addr = match.group(1), int(match.group(2), 16)
            if name in defined:
                continue
            # Odd addresses are flag bits on a pointer, not an instruction.
            if TEXT_LO <= addr < TEXT_HI and addr % 4 == 0:
                at_vram.setdefault(addr, []).append((macro, name))
            else:
                equates[name] = addr

    lines = ["/* generated by tools/retail_equates.py */"]
    for name in sorted(equates):
        lines.append(f".equ {name}, 0x{equates[name]:X}")
    lines.append("")
    OUT.write_text("\n".join(lines))

    found: set[int] = set()
    with TEXT.open() as src, LABELED.open("w") as dst:
        for line in src:
            match = VRAM.search(line)
            if match:
                vram = int(match.group(1), 16)
                for macro, name in at_vram.get(vram, []):
                    dst.write(f"{macro} {name}\n")
                    found.add(vram)
            dst.write(line)

    missing = sorted(set(at_vram) - found)
    print(f"wrote {len(equates)} equates")
    print(f"injected labels at {len(found)} addresses, missing {len(missing)}")
    for vram in missing[:20]:
        names = ", ".join(name for _, name in at_vram[vram])
        print(f"  missing 0x{vram:08X} {names}")


if __name__ == "__main__":
    main()
